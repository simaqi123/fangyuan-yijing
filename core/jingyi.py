def build_tables(con) -> int:
    """把义理概念与关系写入 kb_policy.db（yili / yili_rel 表）。返回写入的概念数。"""
    con.executescript("""
        CREATE TABLE IF NOT EXISTS yili(
          name TEXT PRIMARY KEY, school TEXT, meaning TEXT, basis TEXT, gua TEXT);
        CREATE TABLE IF NOT EXISTS yili_rel(
          src TEXT, rel TEXT, dst TEXT, basis TEXT,
          PRIMARY KEY(src, rel, dst));
    """)
    con.execute("DELETE FROM yili")
    con.execute("DELETE FROM yili_rel")
    con.executemany("INSERT OR REPLACE INTO yili(name,school,meaning,basis,gua) "
                    "VALUES (?,?,?,?,?)", YILI_CONCEPTS)
    con.executemany("INSERT OR REPLACE INTO yili_rel(src,rel,dst,basis) "
                    "VALUES (?,?,?,?)", YILI_RELATIONS)
    return len(YILI_CONCEPTS)


def self_check() -> list:
    """校验：关系两端的非卦象概念需在概念表中；概念/关系无重复。"""
    errs = []
    names = {c[0] for c in YILI_CONCEPTS}
    gua_names = {'乾', '坤', '震', '巽', '坎', '离', '艮', '兑',
                 '泰', '否', '履', '中孚', '无妄', '节', '革', '复', '蒙', '谦',
                 '家人', '师', '随', '大壮', '既济'}
    for src, rel, dst, basis in YILI_RELATIONS:
        if src not in names and src not in gua_names:
            errs.append(f"关系源未知概念：{src}")
        if dst not in names and dst not in gua_names:
            errs.append(f"关系目标未知概念：{dst}")
    if len(names) != len(YILI_CONCEPTS):
        errs.append("概念重名")
    return errs


if __name__ == '__main__':
    errs = self_check()
