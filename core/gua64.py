def anchor_text(row: dict) -> str:
    """构造用于向量匹配的锚点文本（卦名+卦象+卦辞+大象+核心义+现代语义）。"""
    return (
        f"《周易》第{row['gua_no']}卦 {row['name']}卦。卦象：{row['symbol']}，"
        f"上卦{row['up_nature']}，下卦{row['down_nature']}。"
        f"卦辞：{row['ci']}。大象传：{row['xiang']}。"
        f"核心义理：{row['core']}。"
        f"语义范畴：{row['modern']}。"
    )


