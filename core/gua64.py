# 六十四卦对偶关系（通行本序）：1↔64, 2↔63, 3↔62 ... 32↔33
def opposite(no: int) -> int:
    return 65 - no


def _norm_trigram(t: str) -> str:
    """把卦象名（天/雷/风/水/火/山/泽/地）归一到卦名（乾/震/巽/坎/离/艮/兑/坤）。

    历史上巽/巵、乾/天 等异体混用，这里统一收口，避免建表时 KeyError。
    """
    m = {'天': '乾', '地': '坤', '雷': '震', '风': '巽', '水': '坎',
         '火': '离', '山': '艮', '泽': '兑', '巵': '巽', '☰': '乾', '☷': '坤'}
    return m.get(t, t)


def gua_rows():
    """产出 gua 表的行数据。"""
    out = []
    for no, name, up, down, ci, xiang, core, modern in GUA64:
        up = _norm_trigram(up)
        down = _norm_trigram(down)
        up_name, up_sym, _ = TRIGRAM[up]
        down_name, down_sym, _ = TRIGRAM[down]
        out.append({
            'gua_no': no,
            'name': name,
            'symbol': up_sym + down_sym,          # 上卦符 + 下卦符
            'up_trigram': up, 'down_trigram': down,
            'up_nature': up_name, 'down_nature': down_name,
            'ci': ci, 'xiang': xiang, 'core': core, 'modern': modern,
            'opposite': opposite(no),
            'binary': format(TRIGRAM[up][2][0], 'b') + format(TRIGRAM[up][2][1], 'b')
                      + format(TRIGRAM[up][2][2], 'b')
                      + format(TRIGRAM[down][2][0], 'b') + format(TRIGRAM[down][2][1], 'b')
                      + format(TRIGRAM[down][2][2], 'b'),
        })
    return out


