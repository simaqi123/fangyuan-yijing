# ============================================================ 十二律吕 / 黄道次 速查
LV_LU = {x[1]: x[4] for x in XIAOXI}          # 地支 → 律吕
HUANGDAO_CI = {x[1]: x[5] for x in XIAOXI}    # 地支 → 黄道次
XIAOXI_BY_NAME = {x[0]: x for x in XIAOXI}
XIAOXI_BY_NO = {x[1]: x for x in XIAOXI}

# 顺时间方向上的辟卦 phys_pos 递减序列（夏至 64 → 乾 1）
_PHYS_DESC = sorted([x[7] for x in XIAOXI], reverse=True)  # [64,48,40,36,34,33,32,16,8,4,2,1]
_XIAOXI_BY_PHYS = {x[7]: x for x in XIAOXI}


# ============================================================ 圆图物理位置
def _phys_pos(order: int) -> int:
    """由圆图序（fangyuan.yuantu_order，1..64）换算圆图【物理位置】。

    邵雍先天圆图：左半圆(阳仪)乾→复为正序(order 1→32)，右半圆(阴仪)坤→姤为倒序。
    物理相邻序：乾(1)→…→复(32)→坤(64)→剥(63)→…→姤(33)→乾(1)。
    即 order≤32 时 phys=order；order>32 时 phys=97-order（把阴仪翻回物理相邻）。
    """
    if order <= 32:
        return order
    return 97 - order


def phys_pos(no: int) -> int:
    """第 no 卦的圆图物理位置。"""
    from fangyuan import yuantu_order
    return _phys_pos(yuantu_order(no))


def _nearest_xiaoxi_pos(p: int):
    """顺时间方向上，物理位置 p 落入哪个辟卦区间。

    顺时间 = 阳气左旋 = phys 从 64(夏至·姤) 递减到 1(乾)。
    区间（半开，含上界）：(下一辟卦pos, 本辟卦pos] 归本辟卦。
    例如 pos=32 复；pos∈(16,32] 归复；pos=8 泰；pos∈(4,8] 归泰。
    """
    for pos in _PHYS_DESC:          # 从 64 往下降
        if p > pos:                 # 越过该辟卦位置后，落在它的区间内
            return pos
    return 1                        # p==1 及以下 → 乾


def gua_xiaoxi(no: int) -> tuple:
    """返回第 no 卦所属的辟卦全息行（十二消息卦之一）。

    辟卦本身直接命中；杂卦按圆图物理位置归入顺时间最近的辟卦区间。
    """
    if no in XIAOXI_BY_NO:
        return XIAOXI_BY_NO[no]
    p = phys_pos(no)
    key = _nearest_xiaoxi_pos(p)
    return _XIAOXI_BY_PHYS[key]


def gua_jieqi(no: int) -> dict:
    """第 no 卦的历法定位：所属辟卦 + 月 + 地支 + 律吕 + 黄道次 + 节气。"""
    x = gua_xiaoxi(no)
    return {
        "gua_no": no,
        "辟卦": x[0], "月": x[2], "地支": x[3], "律吕": x[4],
        "黄道次": x[5], "节气": "~".join(x[6]),
        "is_xiaoxi": no in XIAOXI_BY_NO,
    }


def jieqi_by_huangjing(deg: float) -> str:
    """太阳黄经度数 → 节气名（就近）。"""
    deg = deg % 360
    best, bestd = "冬至", 360
    for name, d, *_ in JIEQI:
        diff = abs((deg - d + 180) % 360 - 180)
        if diff < bestd:
            best, bestd = name, diff
    return best


def jieqi_of_date(month: int, day: int) -> str:
    """近似公历日期 → 节气（就近，±1 天）。"""
    # 用「日期距各节气的天数差」取最近
    def _day(m, d):
        return m * 31 + d
    cur = _day(month, day)
    best, bestd = "冬至", 10 ** 9
    for name, d, (m, dd), *_ in JIEQI:
        diff = abs(_day(m, dd) - cur)
        if diff < bestd:
            best, bestd = name, diff
    return best


def lv_lu_of_month(zhidi: str) -> str:
    return LV_LU.get(zhidi, "")


def huangdao_ci_of_month(zhidi: str) -> str:
    return HUANGDAO_CI.get(zhidi, "")


def all_gua_jieqi() -> list:
    """产出全部 64 卦的历法行（供建表）。"""
    out = []
    for no in range(1, 65):
        out.append(gua_jieqi(no))
    return out


# ============================================================ 自检
def self_check() -> list:
    errs = []
    # 1) 24 节气齐全且黄经等差 15°
    if len(JIEQI) != 24:
        errs.append(f"节气数 != 24: {len(JIEQI)}")
    degs = sorted([x[1] for x in JIEQI])
    for i in range(24):
        if (degs[(i + 1) % 24] - degs[i]) % 360 != 15:
            errs.append("节气黄经不满足等差 15°")
            break
    # 2) 十二消息卦齐全、卦号唯一
    if len(set(x[1] for x in XIAOXI)) != 12:
        errs.append("消息卦卦号不唯一或不足 12")
    # 3) 辟卦 phys_pos 必须与 fangyuan 推算一致
    from fangyuan import yuantu_order
    for x in XIAOXI:
        no, expect = x[1], x[7]
        got = _phys_pos(yuantu_order(no))
        if got != expect:
            errs.append(f"辟卦 {x[0]} phys_pos 应为 {expect}，推算得 {got}")
    # 4) 关键锚点：复=十一月·含冬至、姤=五月·含夏至、泰=正月·含立春、乾=四月·含立夏
    anchors = {
        "复": ("十一月", "冬至"), "姤": ("五月", "夏至"),
        "泰": ("正月", "立春"), "乾": ("四月", "立夏"),
        "坤": ("十月", "立冬"), "临": ("十二月", "小寒"),
    }
    for name, (month, jq) in anchors.items():
        x = XIAOXI_BY_NAME[name]
        if x[2] != month or jq not in x[6]:
            errs.append(f"锚点 {name} 月/节气不符：{x}")
    # 5) 杂卦归卦：抽验若干非辟卦的落位（屯=初生=冬→复区间？不必强断言，仅验证有归属）
    for no in (3, 5, 7, 10, 30, 42, 55):
        j = gua_jieqi(no)
        if not j["辟卦"]:
            errs.append(f"卦 {no} 未归入辟卦区间")
    # 6) 物理位置覆盖 1..64 且一一对应
    from fangyuan import yuantu_order as _yo
    poses = [_phys_pos(_yo(no)) for no in range(1, 65)]
    if sorted(poses) != list(range(1, 65)):
        errs.append("物理位置未满覆盖 1..64")
    return errs


if __name__ == "__main__":
    errs = self_check()
    if errs:
        print("历法层自检失败：")
        for e in errs:
            print("  -", e)
        raise SystemExit(1)
    print("历法层自检通过：24 节气等差 15°、12 辟卦锚点全对、64 卦物理位置满覆盖")
    print()
    # 抽验关键卦的历法定位
    from fangyuan import yuantu_order
