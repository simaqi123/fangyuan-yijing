"""历法层 jieqi.py —— 二十四节气 · 十二辟卦 · 十二律吕 · 黄道十二次 · 七十二候。

这是「先天方圆图」的【时间】维度落点，把方圆图从静态坐标升级为可推演的天文历法系统。

思想依据（均为汉代以来权威对应，非杜撰）：
  · 二十四节气：太阳黄经每 15° 一节，春分 0°、夏至 90°、秋分 180°、冬至 270°（天文常数）
  · 十二消息卦（十二辟卦）：复(十一月子·冬至) 临 泰 大壮 夬 乾 姤(五月午·夏至) 遁 否 观 剥 坤
  · 十二律吕：黄钟(子) 大吕(丑) 太簇(寅) 夹钟(卯) 姑洗(辰) 仲吕(巳)
               蕤宾(午) 林钟(未) 夷则(申) 南吕(酉) 无射(戌) 应钟(亥)   ——《礼记·月令》《史记·律书》
  · 黄道十二次：星纪 玄枵 娵訾 降娄 大梁 实沈 鹑首 鹑火 鹑尾 寿星 大火 析木
                （与十二辰相配，源自《汉书·律历志》分野次度）
  · 七十二候：每节气三候，取自《逸周书·时训解》《礼记·月令》

关键设计（杜绝「硬配节气」的经典错误）：
  先天圆图卦序（邵雍先天数）与后天卦气（节气）是两套体系，不能线性插值硬拧。
  正确做法——以十二消息卦为【桥梁】：
    1. 辟卦在先天圆图上有固定物理位置（phys_pos）
    2. 辟卦的节气是权威的（复=大雪~冬至、姤=芒种~夏至…）
    3. 其余 52 杂卦按其圆图物理位置，归入「顺时间」方向上最近的辟卦区间，
       即「辟卦为君、杂卦为臣」（汉代卦气「辟卦值月、杂卦附月」之义）。
  这样泰卦精确落正月立春、乾落巳月、复落冬至，全部可程序校验，不自相矛盾。
"""
